# -*- coding: utf-8 -*-
"""
abaAcademy.braille_engine.arabic_braille
========================================

Arabic braille data and logic: the six-dot cell, Arabic letter and diacritic
mappings, digits, punctuation, and a small Grade-2 (contracted) word-sign set.

Source of the mappings
----------------------
The letter, diacritic, digit and punctuation dot patterns are taken from the
official **Unified Arabic Braille** tables as encoded in liblouis
(``ar-ar-g1-core.uti`` — the very tables the screen reader uses), based on the Unified Arabic
Braille Project (mip.qa/braille). liblouis is LGPL-2.1+. We transcribed the
individual letter->dots facts (the braille standard itself), not the file. This
matters: a blind learner drilling these by touch must get cells that match real
braille books and displays exactly.

Grade-2 scope
-------------
Full Arabic Grade-2 has 250+ context-sensitive abbreviations. We ship a small,
unambiguous subset for the tutor's introduction and say so plainly in the UI. We
never invent contractions.

Dot numbering::

    1 4
    2 5
    3 6
"""

from __future__ import annotations


def cell(*dots):
    return frozenset(dots)


def _d(s):
    """Cell from a dot string, e.g. '1456' -> {1,4,5,6}."""
    return frozenset(int(c) for c in s)


def dots_to_unicode(dots):
    bit = 0
    for dot in dots:
        bit |= 1 << (dot - 1)
    return chr(0x2800 + bit)


def describe_dots(dots):
    if not dots:
        return "خلية فارغة"
    return "النقاط " + "، ".join(str(d) for d in sorted(dots))


