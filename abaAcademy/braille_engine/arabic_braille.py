class ArabicBraille:
    """Two-way helper between Arabic text and braille cells."""

    def text_to_cells(self, text, grade2=False):
        out = []
        if grade2:
            words = text.split(" ")
            for wi, word in enumerate(words):
                if word in GRADE2_WORDSIGNS:
                    out.append((word, list(GRADE2_WORDSIGNS[word])))
                else:
                    out.append((word, self._word_cells(word)))
                if wi < len(words) - 1:
                    out.append((" ", [cell()]))
            return out
        for ch in text:
            out.append((ch, self._char_cells(ch)))
        return out

    def _word_cells(self, word):
        cells = []
        for ch in word:
            cells.extend(self._char_cells(ch))
        return cells

    def _char_cells(self, ch):
        if ch in ARABIC_LETTERS:
            return [ARABIC_LETTERS[ch]]
        if ch in ARABIC_HARAKAT:
            return [ARABIC_HARAKAT[ch][1]]
        if ch in DIGIT_LETTERS:
            return [NUMBER_SIGN, DIGIT_LETTERS[ch]]
        if ch in PUNCTUATION:
            return [PUNCTUATION[ch]]
        return [cell()]

    def cell_to_letter(self, dots):
        target = frozenset(dots)
        for letter, pattern in ARABIC_LETTERS.items():
            if pattern == target:
                return letter
        return None

    def name_for_cell(self, dots):
        target = frozenset(dots)
        letter = self.cell_to_letter(target)
        if letter:
            return f"حرف {letter}"
        for _, (name, pattern) in ARABIC_HARAKAT.items():
            if pattern == target:
                return name
        if target == NUMBER_SIGN:
            return "علامة الرقم"
        for sign, pattern in PUNCTUATION.items():
            if pattern == target and sign != " ":
                return f"علامة {sign}"
        if not target:
            return "خلية فارغة"
        return describe_dots(target)
