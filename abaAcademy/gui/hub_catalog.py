"""
abaAcademy.gui.hub_catalog
==========================

Every feature of the main screen, grouped into tabs: a short name (what the
list shows and the screen reader reads), a one-sentence description (shown
under the list and read after a moment), and the hub method that opens it.

Kept as data so the grouping can be reviewed in one place and tested without
a display. A handler of the form ``course:<course_id>`` opens that course
directly in the course browser. ``when`` names a condition the hub evaluates
(an item whose condition is false is left out).
"""

