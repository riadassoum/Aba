def all_features() -> List[Feature]:
    return [f for t in CATALOG for f in t.features]


def handler_names() -> List[str]:
    return [f.handler for f in all_features() if not f.handler.startswith("course:")]


def course_ids() -> List[str]:
    return [f.handler.split(":", 1)[1] for f in all_features() if f.handler.startswith("course:")]
